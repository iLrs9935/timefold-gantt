    private static let patterns: [(NSRegularExpression, [String])] = dictionary.filter { $0.key.contains("%@") }.sorted { $0.key.count > $1.key.count }.compactMap { key, translation in
        let pattern = key.components(separatedBy: "%@").map { NSRegularExpression.escapedPattern(for: $0) }.joined(separator: "(.*?)")
        guard let regex = try? NSRegularExpression(pattern: "^" + pattern + "$", options: .dotMatchesLineSeparators) else { return nil }
        return (regex, translation.components(separatedBy: "%@"))
    }
    static func translate(_ value: String) -> String {
        if let exact = dictionary[value] { return exact }
        let ns = value as NSString
        for (pattern, parts) in patterns {
            if let match = pattern.firstMatch(in: value, range: NSRange(location: 0, length: ns.length)), match.numberOfRanges == parts.count {
                var output = parts[0]
                for index in 1..<parts.count { output += ns.substring(with: match.range(at: index)) + parts[index] }
                return output.replacingOccurrences(of: #"(?<![\d.])1 days\b"#, with: "1 day", options: .regularExpression)
                    .replacingOccurrences(of: #"(?<![\d.])1 tasks\b"#, with: "1 task", options: .regularExpression)
            }
        }
        return value
    }
