final class AppLanguage: ObservableObject {
    static let shared = AppLanguage()
    private let defaults: UserDefaults
    @Published var code: String { didSet { defaults.set(code, forKey: "language"); NotificationCenter.default.post(name: .timefoldLanguageChanged, object: nil) } }
    var isEnglish: Bool { code == "en" }
    var locale: Locale { Locale(identifier: code) }
    private init() {
        defaults = CommandLine.arguments.contains("--preview") ? UserDefaults(suiteName: "Timefold.Preview")! : .standard
        code = CommandLine.arguments.contains("--english") ? "en" : (defaults.string(forKey: "language") ?? ((Locale.preferredLanguages.first ?? "en").hasPrefix("zh") ? "zh" : "en"))
    }
}
